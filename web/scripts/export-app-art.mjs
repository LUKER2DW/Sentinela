// Exports the sign-in page's lighthouse panorama (components/Panorama.tsx)
// and just the CSS it needs into the Android app's bundled pages
// (mobile/www/art/), so the start screen and the offline page wear the same
// scene as the web sign-in. Run after changing the drawing or its styles:
//   cd web && node scripts/export-app-art.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import postcss from "postcss";
import { createServer } from "vite";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(web, "..", "mobile", "www", "art");

const vite = await createServer({ root: web, server: { middlewareMode: true }, appType: "custom", logLevel: "error" });
const { Panorama } = await vite.ssrLoadModule("/src/components/Panorama.tsx");
const { BgDoodles, Anchor, Compass } = await vite.ssrLoadModule("/src/components/Decor.tsx");
const svg = renderToStaticMarkup(createElement(Panorama, { className: "art-pano" }));
// Faint finds behind the page, as on the web app's pages and sign-in.
const doodles = renderToStaticMarkup(
  createElement("div", { className: "app-doodles", "aria-hidden": "true" },
    createElement(BgDoodles),
    createElement(Anchor, { className: "auth-anchor" }),
    createElement(Compass, { className: "auth-compass" })),
);
await vite.close();

// Keep the theme tokens and every rule that styles the scene (pano-*, lh-*,
// fills, hatches), plus the keyframes those rules animate with.
const wanted = /\.pano|\.lh-|\.f-[a-z]|\.hatch-|\.ink|\.faint-ink|\.decor|\.bg-doodles|\.bd[-\s,{]|\.bd$|\.auth-anchor|\.auth-compass/;
const root = postcss.parse(readFileSync(join(web, "src", "styles.css"), "utf8"));
const keep = postcss.root();
const used = new Set();
const pick = (node, into) => {
  if (node.type === "rule") {
    if (/^:root(\[data-theme="(light|dark)"\])?(,\s*:root\[data-theme="light"\])?$/.test(node.selector.replace(/\s+/g, " ").trim())) {
      const r = node.clone({ nodes: [] });
      node.each((d) => {
        if (d.type === "decl" && d.prop.startsWith("--")) r.append(d.clone());
      });
      into.append(r);
    } else if (wanted.test(node.selector)) {
      into.append(node.clone());
      node.walkDecls(/^animation(-name)?$/, (d) => d.value.split(/[\s,]+/).forEach((w) => used.add(w)));
    }
  } else if (node.type === "atrule" && node.name === "media") {
    const m = node.clone({ nodes: [] });
    node.each((c) => {
      pick(c, m);
    });
    if (m.nodes.length) into.append(m);
  } else if (node.type === "atrule" && node.name === "keyframes") {
    into.append(node.clone());
  }
};
root.each((n) => {
  pick(n, keep);
});
keep.walkAtRules("keyframes", (k) => {
  if (!used.has(k.params)) k.remove();
});
keep.walkAtRules("media", (m) => {
  if (!m.nodes.length) m.remove();
});

mkdirSync(out, { recursive: true });
// The web app's typefaces (SIL OFL 1.1), latin subset only.
const fonts = join(web, "node_modules", "@fontsource-variable");
copyFileSync(join(fonts, "fraunces", "files", "fraunces-latin-full-normal.woff2"), join(out, "fraunces.woff2"));
copyFileSync(join(fonts, "figtree", "files", "figtree-latin-wght-normal.woff2"), join(out, "figtree.woff2"));
keep.prepend(
  postcss.parse(`@font-face { font-family: "Fraunces Variable"; font-style: normal; font-display: swap; font-weight: 100 900;
  src: url(fraunces.woff2) format("woff2-variations"); font-variation-settings: normal; }
@font-face { font-family: "Figtree Variable"; font-style: normal; font-display: swap; font-weight: 300 900;
  src: url(figtree.woff2) format("woff2-variations"); }`),
);
writeFileSync(join(out, "panorama.css"), "/* Generated by web/scripts/export-app-art.mjs from web/src/styles.css. Do not edit. */\n" + keep.toString() + "\n");
writeFileSync(
  join(out, "panorama.js"),
  "// Generated by web/scripts/export-app-art.mjs from components/Panorama.tsx. Do not edit.\n" +
    "window.SENTINELA_PANORAMA = " + JSON.stringify(svg) + ";\n" +
    "window.SENTINELA_DOODLES = " + JSON.stringify(doodles) + ";\n",
);
console.log(`art: ${(svg.length / 1024).toFixed(0)} KB svg, ${(keep.toString().length / 1024).toFixed(0)} KB css -> ${out}`);
